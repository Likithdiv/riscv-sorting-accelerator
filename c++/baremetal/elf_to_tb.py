"""Read a linked RV32I ELF and emit a self-contained Vivado testbench.

No hex file or runtime file paths are required by the generated testbench.
Instructions and initialized data go to the CPU's separate memory arrays.
"""

import argparse
from pathlib import Path
import struct


def generate(elf_path, expected):
    blob = elf_path.read_bytes()
    if blob[:7] != b'\x7fELF\x01\x01\x01':
        raise ValueError('Expected a little-endian ELF32 executable')

    header = struct.unpack_from('<HHIIIIIHHHHHH', blob, 16)
    elf_type, machine, _, entry, _, shoff, flags, _, _, _, shsize, shnum, names_index = header
    if elf_type != 2 or machine != 243 or entry != 0 or flags != 0:
        raise ValueError('Expected an RV32I soft-float executable with entry 0 and no extension flags')
    if shsize != 40:
        raise ValueError('Unsupported ELF section-header size')

    sections = [struct.unpack_from('<IIIIIIIIII', blob, shoff + i * shsize)
                for i in range(shnum)]
    name_header = sections[names_index]
    names = blob[name_header[4]:name_header[4] + name_header[5]]

    def cstring(table, offset):
        return table[offset:table.index(b'\0', offset)].decode('ascii')

    code = {}
    data = {}
    symbols = {}
    text_size = 0
    for section in sections:
        name_offset, kind, attributes, address, offset, size, link, _, _, entsize = section
        name = cstring(names, name_offset)
        if kind == 2:  # SHT_SYMTAB
            strings_header = sections[link]
            strings = blob[strings_header[4]:strings_header[4] + strings_header[5]]
            if entsize != 16:
                raise ValueError('Unsupported symbol entry size')
            for position in range(offset, offset + size, entsize):
                sym_name, value, _, _, _, index = struct.unpack_from('<IIIBBH', blob, position)
                if sym_name and index:
                    symbols[cstring(strings, sym_name)] = value

        if not attributes & 2 or size == 0:  # SHF_ALLOC
            continue
        executable = bool(attributes & 4)
        low, high = (0, 0x2000) if executable else (0x2000, 0x4000)
        if address < low or address + size > high:
            raise ValueError(f'Section {name} is outside its CPU memory region')
        if kind == 8:  # SHT_NOBITS: startup clears .bss
            continue
        target = code if executable else data
        for n, byte in enumerate(blob[offset:offset + size]):
            target[address + n] = byte
        if executable:
            text_size += size

    if 'result' not in symbols or not 0x2000 <= symbols['result'] <= 0x3ffc or symbols['result'] % 4:
        raise ValueError('Program must export an aligned 32-bit C-linkage global named result in RAM')
    if not code or max(code) % 4 != 3:
        raise ValueError('Expected complete 32-bit instruction words')

    instructions = {}
    for address in range(0, max(code) + 1, 4):
        word = sum(code.get(address + n, 0) << (8 * n) for n in range(4))
        if word & 3 != 3:
            raise ValueError(f'Non-RV32I instruction alignment/encoding at {address:#x}')
        instructions[address // 4] = word

    initialized_words = {}
    for address, byte in data.items():
        index = address // 4
        word = initialized_words.get(index, 0xa5a5a5a5)
        shift = (address % 4) * 8
        initialized_words[index] = (word & ~(255 << shift)) | (byte << shift)

    lines = ['''`timescale 1ns/1ps

// Generated by c++/baremetal/build.ps1. Edit main.cpp and rebuild instead.
module cpp_tb();

logic clk, rst;
logic halted, trap;
logic [31:0] pc_value, instruction;
integer i;
integer cycles;

cpu_top #(.IMEM_WORDS(4096),.DMEM_WORDS(4096),.IMEM_FILE("")) cpu1(
    .clk(clk),.rst(rst),.halted(halted),.trap(trap),
    .pc_value(pc_value),.instruction(instruction));

initial begin
    clk = 1'b0;
    forever #5 clk = ~clk;
end

always @(posedge clk) begin
    if(rst) cycles <= 0;
    else if(!halted) cycles <= cycles+1;
end

initial begin
    rst = 1'b1;
    #1;
    for(i = 0; i < 4096; i = i+1) begin
        cpu1.imem.memory[i] = 32'h00000013;
        cpu1.dmem.memory[i] = 32'hA5A5A5A5;
    end
''']
    for index, word in instructions.items():
        lines.append(f"    cpu1.imem.memory[{index}] = 32'h{word:08X};\n")
    for index, word in sorted(initialized_words.items()):
        lines.append(f"    cpu1.dmem.memory[{index}] = 32'h{word:08X};\n")

    result_index = symbols['result'] // 4
    lines.append(f'''
    #11;
    rst = 1'b0;
    wait(halted === 1'b1);
    #1;
    if(trap !== 1'b0)
        $fatal(1,"Error: C++ program faulted at PC=%h",pc_value);
    if(cpu1.dmem.memory[{result_index}] !== 32'h{expected:08X})
        $fatal(1,"Error: expected result=%0d, actual=%0d",32'd{expected},cpu1.dmem.memory[{result_index}]);
    if(cpu1.rf.registers[10] !== 32'd0)
        $fatal(1,"Error: main returned a nonzero status");
    $display("C++ result = %0d",cpu1.dmem.memory[{result_index}]);
''')
    for name in ('sum_result', 'product_result', 'sorted_count', 'failure_index', 'accelerator_cycles'):
        if name in symbols:
            lines.append(f'    $display("{name} = %0d",cpu1.dmem.memory[{symbols[name] // 4}]);\n')
    lines.append('''    $display("C++ program passed (%0d cycles including startup and EBREAK)",cycles);
    $finish;
end

initial begin
    #1000000;
    $fatal(1,"Error: C++ program timed out");
end

endmodule: cpp_tb
''')
    return ''.join(lines), text_size, len(data), symbols['result']


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('elf', type=Path)
    parser.add_argument('output', type=Path)
    parser.add_argument('--expected', type=int, required=True)
    args = parser.parse_args()
    if not 0 <= args.expected <= 0xffffffff:
        parser.error('Expected result must fit in an unsigned 32-bit value')
    source, code_size, data_size, result_address = generate(args.elf, args.expected)
    args.output.write_text(source, encoding='ascii')
    print(f'RV32I code: {code_size} bytes; initialized data: {data_size} bytes')
    print(f'result address: {result_address:#06x}; expected: {args.expected}')
